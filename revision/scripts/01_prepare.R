.libPaths(c('revision/R-library',.libPaths()))
library(haven)
library(dplyr)
dir.create('revision/results',showWarnings=FALSE)
f <- 'revision/data/CY08MSP_STU_QQQ.SAV'
meta <- read_sav(f,n_max=0)
labs <- data.frame(variable=names(meta),label=sapply(meta,function(x) {z<-attr(x,'label');if(is.null(z)) '' else z}))
write.csv(labs,'revision/audit/student_dictionary.csv',row.names=FALSE)
vars <- c('CNT','CNTSCHID','CNTSTUID','ST004D01T','GRADE','AGE','IMMIG','ESCS','FAMSUP','RELATST','TEACHSUP','BELONG','ANXMAT','MATHPERS','MATHEFF','MATHEF21','W_FSTUWT',paste0('W_FSTURWT',1:80),paste0('PV',1:10,'MATH'))
items <- grep('^ST(290|291|292|293|034|270|267|268|297|300)',names(meta),value=TRUE)
d <- read_sav(f,col_select=all_of(unique(c(vars,items))))
d <- d[d$CNT %in% c('HKG','TAP'),]
for(n in names(d)) if(is.numeric(d[[n]])) d[[n]]<-as.numeric(d[[n]])
d$CNT <- as.character(d$CNT)
d$FEMALE <- ifelse(is.na(d$ST004D01T),NA,as.integer(d$ST004D01T==1))
stopifnot(!anyDuplicated(paste(d$CNT,d$CNTSTUID)),all(d$W_FSTUWT>0))
saveRDS(d,'revision/data/analysis_raw.rds')
print(table(d$CNT)); print(tapply(d$CNTSCHID,d$CNT,function(x) length(unique(x))))
print(labs[labs$variable %in% c(vars,items) & !grepl('^W_|^PV',labs$variable),],row.names=FALSE)
write.csv(data.frame(economy=d$CNT,school=d$CNTSCHID,student=d$CNTSTUID),'revision/audit/sample_identifiers.csv',row.names=FALSE)
