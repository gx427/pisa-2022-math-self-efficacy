# Draw the archived figures directly, or prepare equivalent CSVs after a full analysis.
reference <- identical(Sys.getenv('APER_REPLAY_FIGURES'), '1')
figure_data <- if (reference) 'reference/figure_data' else 'revision/figures/source_data'
if (!reference) {
  .libPaths(c('revision/R-library', .libPaths()))
  library(dplyr)
  library(tidyr)
  read_result <- function(filename) read.csv(file.path('revision/results', filename))
  dir.create(figure_data, recursive=TRUE, showWarnings=FALSE)
  save_data <- function(data, stem) write.csv(data, file.path(figure_data, paste0(stem, '.csv')), row.names=FALSE)
  labs<-c(MATHEFF='Mathematics self-efficacy',ESCS='Socioeconomic status',FAMSUP='Family support',RELATST='Student–teacher relationships',MATHPERS='Proactive study behaviour',ANXMAT='Mathematics anxiety',BELONG='School belonging')
  des<-read_result('descriptive.csv')
  a<-des%>%filter(variable%in%names(labs))%>%mutate(label=factor(labs[variable],levels=rev(unname(labs))))
  save_data(a, 'Figure_1_weighted_profiles')
  m<-read_result('model_estimates.csv')
  a<-m%>%filter(analysis=='Complete case',grepl('^support:|^full:',term))%>%separate(term,c('model','variable'),sep=':')%>%filter(variable%in%names(labs))%>%mutate(label=factor(labs[variable],levels=rev(unname(labs[-1]))),model=factor(model,levels=c('support','full'),labels=c('a  Support model','b  Full model')))
  save_data(a, 'Figure_2_adjusted_associations')
  ilab<-c(ind_family_behaviour='Family support → proactive behaviour → efficacy',ind_relationship_anxiety='Teacher relationships → anxiety → efficacy',ind_relationship_belonging='Teacher relationships → belonging → efficacy')
  a<-m%>%filter(analysis=='Complete case',term%in%names(ilab))%>%mutate(label=factor(ilab[term],levels=rev(unname(ilab))))
  save_data(a, 'Figure_3_indirect_associations')
  ct<-read_result('economy_contrasts.csv')
  a<-ct%>%filter(analysis=='Complete case',grepl('^full:',term))%>%mutate(variable=sub('full:','',term))%>%filter(variable%in%names(labs))%>%mutate(label=factor(labs[variable],levels=rev(unname(labs[-1]))))
  save_data(a, 'Figure_4_economy_contrasts')
  v<-read_result('school_validation.csv')%>%mutate(model=factor(model,levels=c('Support','Full','Nonlinear'),labels=c('Support model','Full linear model','Full spline model')))
  save_data(v, 'Figure_7_school_validation')
  s<-read_result('sensitivity_models.csv')
  a<-m%>%filter(analysis%in%c('Complete case','20 imputations'),grepl('^full:',term))%>%mutate(term=sub('full:','',term))%>%select(economy,analysis,term,estimate,se,lower,upper)
  a<-bind_rows(a,s%>%filter(analysis=='School fixed effects'))%>%filter(term%in%c('ESCS','MATHPERS','ANXMAT','RELATST'))%>%mutate(variable=factor(labs[term],levels=unname(labs[c('ESCS','MATHPERS','ANXMAT','RELATST')])) )
  save_data(a, 'Figure_6_sensitivity')
  tr<-list()
  for(g in c('HKG','TAP')){imp<-readRDS(paste0('revision/data/imputation_',g,'.rds'));ar<-imp$chainMean;for(v in c('ESCS','FAMSUP','RELATST','ANXMAT'))for(k in 1:20)tr[[paste(g,v,k)]]<-data.frame(economy=g,variable=v,chain=k,iteration=1:10,mean=ar[v,,k])}
  a<-bind_rows(tr)
  save_data(a, 'Figure_5_imputation_traces')
}
python <- Sys.getenv('APER_PYTHON', if (.Platform$OS.type == 'windows') 'python' else 'python3')
status <- system2(python, c('revision/scripts/draw_figures.py', '--data', figure_data))
if (status != 0L) stop('Figure rendering failed')
